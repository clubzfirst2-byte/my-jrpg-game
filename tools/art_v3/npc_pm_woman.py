from npc_pixmap import Fig, t_darker, t_far, t_mirror, v1_back_pose  # noqa: E402

SIDE_ARM = {0: ARM_SIDE_0, 1: ARM_SIDE_F, -1: ARM_SIDE_B}
SKIRT = set("MNOPQR")
SEAM = 58  # the breath: rows above move with the chest; the seam on a plain band of the blouse


def _shift(p, B, U, front=True, still=False):
    def shift(j, i, ch):
        y = 48 + j
        dx = 0
        if p.sway and ch in SKIRT and y > 84 and not still:  # the hem flares and trails
            if front and not (16 <= i < 48):
                dx = round(p.sway * (y - 84) / 16)
            elif not front:
                dx = -round(p.sway * (y - 84) / 16)
        return dx, B + (U if y < SEAM else 0)
    return shift


def _herbs(f, x, y, p, tone=None):
    f.stamp(["x"], x + 2 * p.glint, y, LEG, part="basket", tone=tone)  # the herbs stir


def front(p, back=False, blink=False):
    f = Fig(RAMPS)
    B, U = 2 * p.bob, -2 * p.breath
    shoe = SHOE_BACK if back else SHOE_FRONT
    for (fwd, lift), x0, flip in ((p.near, 21, False), (p.far, 34, True)):
        yv1 = min(55, 55 - lift + (1 if fwd > 1 else 0))
        bottom = 111 - 2 * (55 - yv1)
        f.stamp(shoe, x0, bottom - 5, LEG, part="leg", flip=flip, tone=t_mirror if flip else None)
    body = BODY_BACK if back else BODY_FRONT
    if U or p.sway:  # the body as it stands under the moved rows: no gaps or spikes where the hem sways
        f.stamp(body, 0, 48, LEG, part="body", half_mirror=True, shift=_shift(p, B, 0, still=True))
    f.stamp(body, 0, 48, LEG, part="body", half_mirror=True, shift=_shift(p, B, U))
    ay = 52 + B + U
    r_sw = max(0, p.arm_near if not back else p.arm_far)
    if not back:
        f.stamp(ARM_R, 12, ay - 2 * r_sw, LEG, part="arm")
        f.stamp(ARM_L, 38, ay, LEG, part="arm", flip=True, tone=t_mirror)
        hx, hy = 40, ay + 10
    else:
        f.stamp(ARM_R, 42, ay - 2 * r_sw, LEG, part="arm", flip=True, tone=t_darker)
        f.stamp(ARM_L, 12, ay, LEG, part="arm", tone=t_darker)
        hx, hy = 23, ay + 10
    top = 10 + B + U
    head = HEAD_BACK if back else (HEAD_FRONT_BLINK if blink else HEAD_FRONT)
    f.stamp(head, 0, top, LEG, part="head", half_mirror=True, keep=True)
    t = B + U
    if not back:
        f.stamp(BRAID, 14, 46 + t, LEG, part="hair", keep=True)
        f.stamp(BASKET, hx - 8, hy - 2, LEG, part="basket", keep=True)
        _herbs(f, hx - 5, hy + 2, p)
        f.stamp(["dd", "cc"], hx - 1, hy - 1, LEG, part="arm")  # her fingers round the handle
    else:
        f.stamp(BRAID_BACK, 28, 41 + t, LEG, part="hair", keep=True)  # W2: from under the hair
        f.stamp(BASKET, hx - 8, hy - 2, LEG, part="basket", keep=True)  # v1: the basket in its own tones
        _herbs(f, hx - 5, hy + 2, p)
    return f.finish()


def _shoe_side(f, pose, tone):
    fwd, lift = pose
    sole = 111 - 2 * lift - (2 if lift > 1 else 0)
    f.stamp(SHOE_SIDE_UP if lift > 1 else SHOE_SIDE, 26 + 2 * fwd, sole - 5, LEG, part="leg", tone=tone)


def _basket_arm(f, p, ay, tone=None):
    f.stamp(ARM_SIDE_BASKET, 22, ay, LEG, part="arm", tone=tone, keep=True)
    by = ay + 16 + (2 if p.prop > 0 else 0)
    f.stamp(BASKET, 36, by, LEG, part="basket", tone=tone, keep=True)
    _herbs(f, 39, by + 4, p, tone=tone)
    f.stamp(["dd", "cc"], 44, ay + 13, LEG, part="arm", tone=tone)


def side(p, swap=False, blink=False):
    f = Fig(RAMPS)
    B, U = 2 * p.bob, -2 * p.breath
    ay = 50 + B + U
    _shoe_side(f, p.far, t_far)
    if swap:
        f.stamp(SIDE_ARM[(p.arm_far > 0) - (p.arm_far < 0)], 22, ay, LEG, part="arm", tone=t_darker, keep=True)
    else:
        _basket_arm(f, p, ay, tone=t_darker)
    _shoe_side(f, p.near, None)
    if U or p.sway:
        f.stamp(BODY_SIDE, 0, 48, LEG, part="body", shift=_shift(p, B, 0, front=False, still=True))
    f.stamp(BODY_SIDE, 0, 48, LEG, part="body", shift=_shift(p, B, U, front=False))
    f.stamp(HEAD_SIDE_BLINK if blink else HEAD_SIDE, 0, 10 + B + U, LEG, part="head", keep=True)
    if swap:
        _basket_arm(f, p, ay)
    else:
        f.stamp(SIDE_ARM[(p.arm_near > 0) - (p.arm_near < 0)], 22, ay, LEG, part="arm", keep=True)
        f.stamp(BRAID, 33, 46 + B + U, LEG, part="hair", keep=True)
    return f.finish()


def frame(npc_v1, action, view, i):
    p = npc_v1.pose(action, i)
    if view == "down":
        return front(p, blink=p.blink), False
    if view == "up":
        return front(v1_back_pose(p), back=True), False
    if view == "right":
        return side(p, blink=p.blink), False
    return side(p, swap=True, blink=p.blink), True
