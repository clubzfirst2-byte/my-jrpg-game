from npc_pixmap import Fig, t_darker, t_far, t_mirror, v1_back_pose  # noqa: E402

SIDE_LEGS = {(0, 0): LEG_SIDE_p0_0, (2, 0): LEG_SIDE_p2_0, (-2, 0): LEG_SIDE_m2_0, (2, 1): LEG_SIDE_p2_1,
             (-2, 1): LEG_SIDE_m2_1, (0, 2): LEG_SIDE_p0_2}
SEAM = 60  # the breath: the seam on the plain cape, above its rim and the sash


def _body_shift(p, B, U, side=False, still=False):
    def shift(j, i, ch):
        y = 48 + j
        dx = 0
        if p.sway and y > 80 and not still:  # the hem sways: one texel per 12 rows, the whole row (no spikes)
            d = round(p.sway * (y - 80) / 12)
            if side:
                dx = -d
            elif i < 20 or i > 43:
                dx = d if i > 43 else -d
        return dx, B + (U if y < SEAM else 0)
    return shift


def _lag(sign, start, step):
    """The hair trails the sway: the whole piece moves one texel (rows moved by different amounts would
    leave 1-texel spikes on the outline)."""
    def shift(j, i, ch):
        return sign, 0
    return shift


def front(p, back=False, blink=False):
    f = Fig(RAMPS)
    B, U = 2 * p.bob, -2 * p.breath
    t = B + U
    top = 4 + t
    legmap = LEG_BACK if back else LEG_FRONT
    for (fwd, lift), x0, flip in ((p.near, 23, False), (p.far, 33, True)):
        yv1 = min(55, 55 - lift + (1 if fwd > 1 else 0))
        bottom = 111 - 2 * (55 - yv1)
        f.stamp(legmap, x0, bottom - len(legmap) + 1, LEG, part="leg", flip=flip, tone=t_mirror if flip else None,
                keep=True)
    sw = (p.sway > 0) - (p.sway < 0)
    if not back:  # the long hair behind her shoulders, its tips lagging
        f.stamp(FLANK, 6, 40 + t, LEG, part="hair", keep=True, shift=_lag(-sw, 22, 6))
        f.stamp(FLANK, 48, 40 + t, LEG, part="hair", flip=True, tone=t_mirror, keep=True, shift=_lag(sw, 22, 6))
    else:
        f.stamp(FLANK_BACK, 6, 48 + t, LEG, part="hair", keep=True, shift=_lag(-sw, 12, 6))
        f.stamp(FLANK_BACK, 48, 48 + t, LEG, part="hair", flip=True, tone=t_mirror, keep=True, shift=_lag(sw, 12, 6))
    body = BODY_BACK if back else BODY_FRONT
    if U or p.sway:  # the body as it stands under the moved rows: no gaps where the hem flares
        f.stamp(body, 0, 48, LEG, part="body", half_mirror=True, shift=_body_shift(p, B, 0, still=True))
    f.stamp(body, 0, 48, LEG, part="body", half_mirror=True, shift=_body_shift(p, B, U), keep=True)
    if not back:
        f.stamp(ARMS_FRONT, 12, 64 + t, LEG, part="arm", keep=True)
    else:
        f.stamp(ELBOW, 14, 66 + t, LEG, part="arm", tone=t_darker, keep=True)
        f.stamp(ELBOW, 47, 66 + t, LEG, part="arm", flip=True, tone=t_darker, keep=True)
    f.stamp(HEAD_BACK if back else HEAD_FRONT, 0, top, LEG, part="head", half_mirror=True, keep=True)
    if not back:
        f.stamp(EYE_SKIN, 14, top + 25, LEG, part="head", keep=True)
        f.stamp(EYE_SKIN, 40, top + 25, LEG, part="head", keep=True)
        f.stamp(EYE_SHUT_L if blink else EYE_L, 14, top + 25, LEG, part="head", keep=True)
        f.stamp(EYE_SHUT_R if blink else EYE_R, 40, top + 25, LEG, part="head", keep=True)
        f.stamp(SMILE, 29, top + 39, LEG, part="head", keep=True)
        f.stamp(JEWEL, 27, top + 9, LEG, part="jewel", keep=True)
        f.stamp(["x"], 30 + p.glint, top + 13, LEG, part="jewel", keep=True)  # the stone's shine moves
        f.stamp(BRAID, 10, top + 24, LEG, part="hair", keep=True, shift=_lag(-sw, 28, 3))
        f.stamp(BRAID, 46, top + 24, LEG, part="hair", flip=True, tone=t_darker, keep=True, shift=_lag(sw, 28, 3))
        f.stamp(CLASP, 29, 49 + t, LEG, part="clasp", keep=True)
        f.stamp(VEIN, 20, 71 + t, LEG, part="sash", keep=True)
    else:
        f.stamp(["l"], 20 + 8 * p.glint, top + 14, LEG, part="head", keep=True)  # a glint runs round the circlet
        f.stamp(VEIN, 20, 71 + t, LEG, part="sash", keep=True)
        f.stamp(FALL, 0, 70 + t, LEG, part="hair", half_mirror=True, keep=True)
    return f.finish()


def _side_leg(f, pose, tone):
    rows = SIDE_LEGS[pose]
    lift = pose[1]
    sole = 111 - 2 * lift - (2 if lift > 1 else 0)
    f.stamp(rows, 18, sole - len(rows) + 1, LEG, part="leg", tone=tone, keep=True)


def side(p, blink=False):
    f = Fig(RAMPS)
    B, U = 2 * p.bob, -2 * p.breath
    t = B + U
    top = 4 + t
    sw = (p.sway > 0) - (p.sway < 0)
    _side_leg(f, p.far, t_far)
    _side_leg(f, p.near, None)
    f.stamp(ARM_SIDE_FAR, 32, 66 + t, LEG, part="arm", tone=t_darker, keep=True)
    f.stamp(BRACELET, 37, 69 + t, LEG, part="arm", tone=t_darker, keep=True)  # on her left (far) wrist
    if U or p.sway:
        f.stamp(BODY_SIDE, 0, 48, LEG, part="body", shift=_body_shift(p, B, 0, side=True, still=True))
    f.stamp(BODY_SIDE, 0, 48, LEG, part="body", shift=_body_shift(p, B, U, side=True), keep=True)
    f.stamp(BACKHAIR, 6, 48 + t, LEG, part="hair", keep=True, shift=_lag(-sw, 12, 6))
    f.stamp(HEAD_SIDE_BLINK if blink else HEAD_SIDE, 0, top, LEG, part="head", keep=True)
    f.stamp(STAR_SIDE, 42, top + 12, LEG, part="jewel", keep=True)
    f.stamp(ARM_SIDE_NEAR, 28, 62 + t, LEG, part="arm", keep=True)
    f.stamp(CLASP, 31, 51 + t, LEG, part="clasp", keep=True)
    f.stamp(BRAID, 24, top + 22, LEG, part="hair", keep=True, shift=_lag(-sw, 28, 3))
    return f.finish()


def frame(npc_v1, action, view, i):
    """Left is not made (the game mirrors right)."""
    p = npc_v1.pose(action, i)
    if view == "down":
        return front(p, blink=p.blink), False
    if view == "up":
        return front(v1_back_pose(p), back=True), False
    return side(p, blink=p.blink), False
