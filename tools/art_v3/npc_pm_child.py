from npc_pixmap import Fig, t_darker, t_far, t_mirror, v1_back_pose  # noqa: E402

SIDE_LEGS = {(0, 0): LEG_SIDE_p0_0, (3, 0): LEG_SIDE_p3_0, (-3, 0): LEG_SIDE_m3_0, (3, 1): LEG_SIDE_p3_1,
             (-3, 1): LEG_SIDE_m3_1, (0, 2): LEG_SIDE_p0_2}
HANG = {0: ARM_SIDE_HANG_0, 1: ARM_SIDE_HANG_F, -1: ARM_SIDE_HANG_B}


def _breath(B, U, top, below=86):
    def shift(j, i, ch):
        return 0, B + (U if top + j < below else 0)
    return shift


def _vanes(f, cx, cy, p, tone=None):
    phase = (p.glint + (p.prop != 0)) % 2
    f.stamp(VANE_P if phase == 0 else VANE_X, cx - 7, cy - 7, LEG, part="pinwheel", tone=tone)


def front(p, back=False, blink=False):
    f = Fig(RAMPS)
    B, U = 2 * p.bob, -2 * p.breath
    legmap = LEG_BACK if back else LEG_FRONT
    for (fwd, lift), x0, flip in ((p.near, 19, False), (p.far, 35, True)):
        yv1 = min(55, 55 - lift + (1 if fwd > 1 else 0))
        bottom = 111 - 2 * (55 - yv1)
        f.stamp(legmap, x0, bottom - len(legmap) + 1, LEG, part="leg", flip=flip, tone=t_mirror if flip else None)
    body = BODY_BACK if back else BODY_FRONT
    if U:
        f.stamp(body, 0, 70, LEG, part="body", half_mirror=True, shift=_breath(B, 0, 70))
    f.stamp(body, 0, 70, LEG, part="body", half_mirror=True, shift=_breath(B, U, 70))
    if not back:
        f.stamp(STRAP, 19, 72 + B + U, LEG, part="strap")
    ay = 74 + B + U
    r_sw = max(0, p.arm_near if not back else p.arm_far)
    l_sw = max(0, p.arm_far if not back else p.arm_near)
    if not back:
        f.stamp(ARM, 14, ay - 2 * r_sw, LEG, part="arm")
        f.stamp(ARM, 42, ay - 2 * l_sw, LEG, part="arm", flip=True, tone=t_mirror)
        hx, hy = 17, ay - 2 * r_sw + 14
    else:
        f.stamp(ARM, 42, ay - 2 * r_sw, LEG, part="arm", flip=True, tone=t_darker)
        f.stamp(ARM, 14, ay - 2 * l_sw, LEG, part="arm", tone=t_darker)
        hx, hy = 46, ay - 2 * r_sw + 14
    top = 34 + B + U
    head = HEAD_BACK if back else (HEAD_FRONT_BLINK if blink else HEAD_FRONT)
    f.stamp(head, 0, top, LEG, part="head", half_mirror=True)
    if not back:
        f.stamp(BAG, 38, 86 + B, LEG, part="bag")
        f.stamp(COWLICK, 32, top - 7, LEG, part="hair")
        f.stamp(STICK_F, hx - 8, hy - 14, LEG, part="pinwheel")
        _vanes(f, hx - 8, hy - 18, p)
    else:
        f.stamp(STRAP, 15, 72 + B + U, LEG, part="strap", flip=True, tone=t_darker)
        f.stamp(BAG, 16, 86 + B, LEG, part="bag", flip=True, tone=t_darker)
        f.stamp(COWLICK, 24, top - 7, LEG, part="hair", flip=True)
        f.stamp(STICK_F, hx, hy - 14, LEG, part="pinwheel", flip=True, tone=t_darker)
        _vanes(f, hx + 8, hy - 18, p, tone=t_darker)
    return f.finish()


def _side_leg(f, pose, tone):
    rows = SIDE_LEGS[pose]
    lift = pose[1]
    sole = 111 - 2 * lift - (2 if lift > 1 else 0)
    f.stamp(rows, 20, sole - len(rows) + 1, LEG, part="leg", tone=tone)


def _pin_arm(f, ay, p, tone=None):
    f.stamp(ARM_SIDE_PIN, 24, ay, LEG, part="arm", tone=tone)
    f.stamp(STICK_S, 47, ay + 1, LEG, part="pinwheel", tone=tone)
    f.stamp(FIST_SIDE, 45, ay + 11, LEG, part="arm", tone=tone)
    _vanes(f, 55, ay - 3, p, tone=tone)


def side(p, swap=False, blink=False):
    f = Fig(RAMPS)
    B, U = 2 * p.bob, -2 * p.breath
    ay = 72 + B + U
    top = 34 + B + U
    _side_leg(f, p.far, t_far)
    if swap:
        _pin_arm(f, ay, p, tone=t_darker)
    else:
        f.stamp(HANG[(p.arm_far > 0) - (p.arm_far < 0)], 18, ay, LEG, part="arm", tone=t_darker)
    if U:
        f.stamp(BODY_SIDE, 0, 70, LEG, part="body", shift=_breath(B, 0, 70))
    f.stamp(BODY_SIDE, 0, 70, LEG, part="body", shift=_breath(B, U, 70))
    _side_leg(f, p.near, None)
    f.stamp(HEAD_SIDE_BLINK if blink else HEAD_SIDE, 0, top, LEG, part="head")
    f.stamp(COWLICK, 25, top - 7, LEG, part="hair", flip=True)
    if swap:
        f.stamp(HANG[(p.arm_near > 0) - (p.arm_near < 0)], 18, ay, LEG, part="arm")
        f.stamp(STRAP_SIDE_L, 26, ay, LEG, part="strap")
        f.stamp(BAG, 24, 84 + B, LEG, part="bag")
    else:
        f.stamp(STRAP_SIDE, 27, ay, LEG, part="strap")
        _pin_arm(f, ay, p)
    return f.finish()


def frame(npc_v1, action, view, i):
    p = npc_v1.pose(action, i)
    if view == "down":
        return front(p, blink=p.blink), False
    if view == "up":
        return front(v1_back_pose(p), back=True), False
    if view == "right":
        return side(p, blink=p.blink), False
    return side(p, swap=True, blink=p.blink), True
