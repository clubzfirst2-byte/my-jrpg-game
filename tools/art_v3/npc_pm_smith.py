from npc_pixmap import Fig, t_darker, t_far, t_mirror, v1_back_pose  # noqa: E402

SIDE_LEGS = {(0, 0): LEG_SIDE_p0_0, (3, 0): LEG_SIDE_p3_0, (-3, 0): LEG_SIDE_m3_0, (3, 1): LEG_SIDE_p3_1,
             (-3, 1): LEG_SIDE_m3_1, (0, 2): LEG_SIDE_p0_2}
SIDE_ARM = {0: ARM_SIDE_0, 1: ARM_SIDE_F, -1: ARM_SIDE_B}
SEAM = 64  # the breath: the seam on the plain shirt and apron below the bib's pocket, above the waist band
# (round 4d: was 60, under the pocket, which doubled its lower edge)


def _breath(B, U):
    def shift(j, i, ch):
        return 0, B + (U if 40 + j < SEAM else 0)
    return shift


def _hammer(f, x, y, glint, tone=None):
    f.stamp(HAMMER, x, y, LEG, part="hammer", tone=tone, keep=True)
    if tone is None:
        f.stamp(["x"], x + 6 + 2 * glint, y + 1, LEG, part="hammer", keep=True)  # the light runs along the head


def front(p, back=False, blink=False):
    f = Fig(RAMPS)
    B, U = 2 * p.bob, -2 * p.breath
    legmap = LEG_BACK if back else LEG_FRONT
    for (fwd, lift), x0, flip in ((p.near, 16, False), (p.far, 34, True)):
        yv1 = min(55, 55 - lift + (1 if fwd > 1 else 0))
        bottom = 111 - 2 * (55 - yv1)
        f.stamp(legmap, x0, bottom - len(legmap) + 1, LEG, part="leg", flip=flip, tone=t_mirror if flip else None,
                keep=True)
    body = BODY_BACK if back else BODY_FRONT
    if U:
        f.stamp(body, 0, 40, LEG, part="body", half_mirror=True, shift=_breath(B, 0))
    f.stamp(body, 0, 40, LEG, part="body", half_mirror=True, shift=_breath(B, U), keep=True)
    if back:  # the straps' V moves whole with the chest (round 4d: no split tip when breathing)
        f.stamp(STRAPS_BACK, 0, 42 + B + U, LEG, part="body", half_mirror=True, keep=True)
    ay = 46 + B + U
    r_sw = max(0, p.arm_near if not back else p.arm_far)
    l_sw = max(0, p.arm_far if not back else p.arm_near)
    if not back:
        f.stamp(ARM, 6, ay - 2 * r_sw, LEG, part="arm", keep=True)
        f.stamp(ARM, 46, ay - 2 * l_sw, LEG, part="arm", flip=True, tone=t_mirror, keep=True)
    else:
        f.stamp(ARM, 46, ay - 2 * r_sw, LEG, part="arm", flip=True, tone=t_darker, keep=True)
        f.stamp(ARM, 6, ay - 2 * l_sw, LEG, part="arm", tone=t_darker, keep=True)
    head = HEAD_BACK if back else (HEAD_FRONT_BLINK if blink else HEAD_FRONT)
    f.stamp(head, 0, 4 + B + U, LEG, part="head", half_mirror=True, keep=True)
    _hammer(f, 12 if not back else 38, 68 + B, p.glint)
    return f.finish()


def _side_leg(f, pose, tone):
    rows = SIDE_LEGS[pose]
    lift = pose[1]
    sole = 111 - 2 * lift - (2 if lift > 1 else 0)
    f.stamp(rows, 16, sole - len(rows) + 1, LEG, part="leg", tone=tone, keep=True)


def side(p, swap=False, blink=False):
    f = Fig(RAMPS)
    B, U = 2 * p.bob, -2 * p.breath
    ay = 45 + B + U
    top = 4 + B + U
    _side_leg(f, p.far, t_far)
    f.stamp(SIDE_ARM[(p.arm_far > 0) - (p.arm_far < 0)], 14, ay, LEG, part="arm", tone=t_darker, keep=True)
    _side_leg(f, p.near, None)
    if U:
        f.stamp(BODY_SIDE, 0, 40, LEG, part="body", shift=_breath(B, 0))
    f.stamp(BODY_SIDE, 0, 40, LEG, part="body", shift=_breath(B, U), keep=True)
    f.stamp(HEAD_SIDE_BLINK if blink else HEAD_SIDE, 0, top, LEG, part="head", keep=True)
    f.stamp(SIDE_ARM[(p.arm_near > 0) - (p.arm_near < 0)], 14, ay, LEG, part="arm", keep=True)
    f.stamp(TAILS, 6 - 2 * p.glint, top + 12, LEG, part="band", keep=True)  # the band's tails sway
    if not swap:
        _hammer(f, 24, 68 + B, p.glint)
    return f.finish()


def frame(npc_v1, action, view, i):
    """Left is not made (the game mirrors right)."""
    p = npc_v1.pose(action, i)
    if view == "down":
        return front(p, blink=p.blink), False
    if view == "up":
        return front(v1_back_pose(p), back=True), False
    return side(p, blink=p.blink), False
