// Freezes how older versions of the game listed the map's objects (P10.3, for save compatibility).
//
// Saves from P8 to P10.2 named changed objects (a broken jar, a burnt tree) by their position in the
// list of map objects. That list changed with the map (P9 cleared trees for the village, P10.1 added
// house walls and furniture), so an old save is read against the list of the version that wrote it.
// The game cannot tell which version that was, so src/save (migration to schema 3) tries all of them
// and keeps a change only when they agree. This script rebuilds the lists from git history:
//
//   node tools/gen_legacy_objects.mjs   ->   src/save/legacyObjects.js
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
/** The merge commit of each version whose saves used index keys. */
const ERAS = { p8: '9d3be4d', p9: '3e0ef80', p10: '6218d99' };

const out = {};
for (const [era, commit] of Object.entries(ERAS)) {
  const dir = mkdtempSync(join(tmpdir(), `legacy-${era}-`));
  const files = ['src/game/world/tilemap.js', 'src/game/world/world.js', 'src/game/world/maps/island.js', 'src/game/world/maps/regions.js'];
  for (const f of files) {
    const text = execFileSync('git', ['show', `${commit}:${f}`], { cwd: root, encoding: 'utf8' });
    mkdirSync(dirname(join(dir, f)), { recursive: true });
    writeFileSync(join(dir, f), text);
  }
  const { parseMap } = await import(join(dir, 'src/game/world/tilemap.js'));
  const { WORLD } = await import(join(dir, 'src/game/world/world.js'));
  // As createGameState did: the parsed map's objects, then the environment objects.
  const objects = [...parseMap(WORLD).objects, ...(WORLD.envObjects ?? [])];
  out[era] = objects.map((o) => `${o.type}@${o.tx},${o.ty}`).join(' ');
  console.log(era, commit, objects.length);
}

const body = `// @ts-check
// GENERATED by tools/gen_legacy_objects.mjs: how P8, P9 and P10.1-P10.2 listed the map's objects
// ("type@tx,ty" in list order). Used to read world differences from saves of those versions.

/** @type {Record<string, string>} */
export const LEGACY_OBJECTS = ${JSON.stringify(out, null, 1)};
`;
writeFileSync(join(root, 'src/save/legacyObjects.js'), body);
console.log('wrote src/save/legacyObjects.js', body.length, 'bytes');
