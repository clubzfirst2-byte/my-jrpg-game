def grid(text):
    rows = text.strip("\n").split("\n")
    for r in rows:
        assert len(r) == 32, (len(r), r)
    return rows


FRONT_ROWS, BACK_ROWS, SIDE_ROWS = grid(FRONT), grid(BACK), grid(SIDE)


GROUND = 53  # the lowest row the cloak's hem may reach (the boots stay visible below it)


def _row(y, b, last):
    """Where map row y lands. Crouching deep (a big bob) would push the hem through the ground:
    then the cloak below the belt (row 34) is gathered up so the hem rests just above the boots."""
    if b <= 0 or last + b <= GROUND:
        return y + b
    if y < 34:
        return y + b
    return round(34 + b + (y - 34) * (GROUND - 34 - b) / (last - 34))


def _stamp(c, rows, b, shift):
    """shift(y, x, ch) -> dx for that pixel (y is the frame row without the bob)."""
    last = TOP + len(rows) - 1
    for i, row in enumerate(rows):
        y = TOP + i
        ty = _row(y, b, last)
        for x, ch in enumerate(row):
            if ch == ".":
                continue
            m, t = MATS[ch]
            c.put(x + shift(y, x, ch), ty, m, t)


def body_front(c, b, sway, back=False):
    """Front (or back) body. The lower cloak (rows 41-46) swings with sway; the tunic stays."""
    def shift(y, x, ch):
        if y < 41 or ch in "abcdevwxyz":
            return 0
        return round(sway * (y - 40) / 6)
    _stamp(c, BACK_ROWS if back else FRONT_ROWS, b, shift)


def body_side(c, b, lean, sway, flare):
    """Facing right: the shoulders lean forward, the cloak's tail trails back (left)."""
    def shift(y, x, ch):
        dx = round(lean * max(0, 34 - y) / 12)
        if ch in "01234fghij" and x <= 12 and y >= 34:
            dx -= round((sway + flare) * (y - 33) / 12)
        return dx
    _stamp(c, SIDE_ROWS, b, shift)
