INK = {"e": "#24223a", "i": "#2a78d0", "I": "#1a3c86", "w": "#f0fbff", "W": "#d8cfc6",
       "n": "#4e2e1a", "m": "#a8584e", "r": "#f0a888"}


def grid(text):
    rows = [r for r in text.strip("\n").split("\n")]
    for r in rows:
        assert len(r) == 32, (len(r), r)
    return rows


def stamp(c, rows, top, dx=0, sway=0, swing_rows=()):
    """Places a map; rows listed in swing_rows shift by `sway` (hair tips lagging behind)."""
    for y, row in enumerate(rows):
        off = dx + (sway if y in swing_rows else 0)
        for x, ch in enumerate(row):
            px, py = x + off, top + y
            if ch == ".":
                continue
            if ch in "01234":
                c.put(px, py, "hair", int(ch))
            elif ch in "abcd":
                c.put(px, py, "skin", "abcd".index(ch) + 1)
            else:
                c.put(px, py, "skin", 2)
                c.paint(px, py, INK[ch])


FRONT_ROWS, BACK_ROWS, SIDE_ROWS = grid(FRONT), grid(BACK), grid(SIDE)


def head_front(c, top, sway=0, blink=False, dx=0):
    rows = FRONT_ROWS
    if blink:  # eyes closed: the lash line drops onto the eye, the eye area becomes skin
        rows = [r.replace("I", "c").replace("i", "c").replace("w", "c").replace("W", "c") if y in (16, 17) else r
                for y, r in enumerate(rows)]
        rows[16] = rows[16][:7] + "eeee" + rows[16][11:17] + "eeee" + rows[16][21:]
        rows[15] = rows[15].replace("e", "c")
    s = 1 if sway > 0 else -1 if sway < 0 else 0
    stamp(c, rows, top, dx, s, swing_rows=(19, 20, 21))


def head_back(c, top, sway=0, dx=0):
    s = 1 if sway > 0 else -1 if sway < 0 else 0
    stamp(c, BACK_ROWS, top, dx, s, swing_rows=(19, 20, 21))


def head_side(c, top, sway=0, dx=0, blink=False):
    rows = SIDE_ROWS
    if blink:
        rows = list(rows)
        rows[15] = rows[15].replace("e", "c")
        rows[16] = rows[16].replace("I", "e").replace("i", "e").replace("w", "e").replace("W", "c")
        rows[17] = rows[17].replace("I", "c").replace("i", "c")
    s = -1 if sway > 0 else 0  # facing right: the back hair trails left
    stamp(c, rows, top, dx, s, swing_rows=(18, 19, 20, 21))
